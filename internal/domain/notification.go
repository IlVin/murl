// Package domain содержит базовые сущности и типы данных,
// определяющие бизнес-логику приложения murl.
package domain

// Notification представляет собой универсальный контейнер для уведомлений в системе.
// Данная структура используется для передачи сообщений между бизнес-логикой
// и адаптерами аудита (File, URL и др.).
type Notification struct {
	// Message содержит тело уведомления в сыром виде (обычно JSON).
	// Использование []byte позволяет доменному слою оставаться независимым
	// от конкретных форматов сериализации внешних систем.
	Message []byte
}
