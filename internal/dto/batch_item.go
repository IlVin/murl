package dto

// BatchItem представляет собой элемент пакетной операции сокращения ссылок.
// Используется как для входных данных, так и для формирования ответа при массовой обработке.
type BatchItem struct {
	// CorrelationID — произвольный идентификатор строки, предоставленный клиентом.
	// Служит для сопоставления запроса и ответа в асинхронных или пакетных операциях.
	CorrelationID string `json:"correlation_id"`
	// OriginalURL — исходный длинный URL.
	// Может быть пустым в ответе, если клиент уже знает его.
	OriginalURL string `json:"original_url,omitempty"`
	// ShortURL — результат сокращения для данной строки.
	ShortURL string `json:"short_url,omitempty"`
	// ConflictFlag указывает на наличие конфликта уникальности в базе данных.
	// Не сериализуется в JSON (используется только для внутренней логики бизнес-слоя).
	ConflictFlag bool `json:"-"`
	// Err содержит описание ошибки обработки конкретного элемента, если она возникла.
	Err string `json:"err,omitempty"`
}
